function file(name: string, pages: number, sizeLabel = "4,2 MB", kind: DemoFile["kind"] = "pdf"): DemoFile {
  return { name, pages, sizeLabel, kind, state: "optimo" };
}

const basicSpecs = (pages: number): PrintSpecs => ({
  ...defaultSpecs,
  pages,
  notes: "Sin abrochar. Retiro por mostrador.",
});

function order(input: Omit<Order, "code" | "specs" | "readyAt"> & { specs?: PrintSpecs; readyAt?: string }): Order {
  const specs = input.specs ?? basicSpecs(input.file.pages);
  return {
    ...input,
    specs,
    code: `FADU-${String(212 + input.ticket).padStart(4, "0")}`,
    readyAt: input.readyAt ?? addMinutes(input.createdAt, 8),
  };
}

